bool dfl::chapter_two::mailbox_refresh_detail::InstallImage(
    unsigned char* image,std::size_t bytes,PatchWriter write) noexcept
{
    if(!image||bytes!=ImageSize||!write||
        reinterpret_cast<std::uintptr_t>(image)>std::numeric_limits<std::uintptr_t>::max()-ImageSize)return false;
    for(const auto& signature:Context)
        if(std::memcmp(image+signature.offset,signature.data,signature.size))return false;
    auto* append=image+AppendOffset;
    if(std::memcmp(append,Append,PatchWithinAppend)||
        std::memcmp(append+PatchWithinAppend+PatchSize,Append+PatchWithinAppend+PatchSize,sizeof(Append)-PatchWithinAppend-PatchSize))return false;
    auto* patch=append+PatchWithinAppend;
    std::array<unsigned char,PatchSize> replacement{0xe8,0,0,0,0,0x90,0x90};
    const auto address=reinterpret_cast<std::uintptr_t>(patch);
    const auto delta=static_cast<std::uint32_t>(reinterpret_cast<std::uintptr_t>(&MarkBothMailboxesDirty)-address-5);
    std::memcpy(replacement.data()+1,&delta,sizeof(delta));
    if(std::memcmp(patch,replacement.data(),PatchSize)==0)return true;
    if(std::memcmp(patch,Append+PatchWithinAppend,PatchSize))return false;
    if(write(address,replacement.data(),replacement.size()))return true;
    // WriteBytes can fail after copying when protection/cache restoration fails.
    write(address,Append+PatchWithinAppend,PatchSize);
    return false;
}

bool dfl::chapter_two::InstallMailboxRefresh(unsigned char* image,std::size_t bytes) noexcept
{
    return image==reinterpret_cast<unsigned char*>(0x400000)&&
        mailbox_refresh_detail::InstallImage(image,bytes,memory_patch::WriteBytes);
}
