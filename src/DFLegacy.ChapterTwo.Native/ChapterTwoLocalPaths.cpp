bool dfl::chapter_two::local_paths_detail::InstallImage(unsigned char* image,std::size_t bytes,PatchWriter write) noexcept
{
    if(!image||bytes!=ImageSize||!write||
        reinterpret_cast<std::uintptr_t>(image)>std::numeric_limits<std::uintptr_t>::max()-ImageSize)return false;
    if(std::memcmp(image+0x16b0,Resolver,sizeof(Resolver))||
        std::memcmp(image+0x6ea6d8,"%s%s",5)||std::memcmp(image+0x6ea6e0,"\\",2)||
        std::memcmp(image+0x6ea6f4,"Low\\DNF\\",9)||
        std::memcmp(image+Scratch,Empty.data(),PathCapacity)||
        std::memcmp(image+Prefix+1,Empty.data(),PathCapacity-1))return false;
    if(image[Prefix]==LocalMode[0])return true;
    // A populated or partly initialized prefix is not ours to overwrite.
    if(image[Prefix]!=0)return false;
    const auto address=reinterpret_cast<std::uintptr_t>(image+Prefix);
    if(write(address,LocalMode,sizeof(LocalMode)))return true;
    // Include failures reported after mutation (protection or cache errors).
    write(address,Empty.data(),sizeof(LocalMode));return false;
}

bool dfl::chapter_two::InstallLocalPaths(unsigned char* image,std::size_t bytes) noexcept
{
    return image==reinterpret_cast<unsigned char*>(0x400000)&&
        local_paths_detail::InstallImage(image,bytes,memory_patch::WriteBytes);
}
