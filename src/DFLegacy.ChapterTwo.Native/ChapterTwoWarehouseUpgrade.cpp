#include "ChapterTwoWarehouseUpgrade.h"
#include <cstring>

bool dfl::chapter_two::InstallWarehouseUpgradeButton(unsigned char* image, std::size_t bytes) noexcept
{
    if (!image || bytes != 0xe57000) return false;

    // The non-max warehouse layout shows the button, then disables it. Its
    // original click path already checks the button, current grade and mall.
    constexpr unsigned char render[]{0x55,0x8b,0xec,0x81,0xec,0xbc,0x00,0x00,0x00,0x8b,0x45,0x08,0x57,0x8b,0xf9};
    constexpr unsigned char renderSlot[]{0x30,0x28,0x90,0x00};
    constexpr unsigned char grade[]{
        0x83,0xfe,0x07,0x7c,0x0f,0x8b,0x57,0x2c,0xc6,0x82,0x18,0x01,0x00,0x00,0x00,
        0xe9,0xac,0x00,0x00,0x00,0x8b,0x47,0x2c,0xc6,0x80,0x18,0x01,0x00,0x00,0x01};
    constexpr unsigned char click[]{
        0x8b,0x46,0x10,0x8b,0x88,0x88,0x12,0x00,0x00,0x39,0x59,0x1c,0x75,0x49,
        0x8b,0x46,0x2c,0x8a,0x88,0x19,0x01,0x00,0x00,0x05,0x08,0x01,0x00,0x00,
        0x84,0xc9,0x74,0x37,0x8b,0x15,0xbc,0xdf,0xd4,0x00,0x3b,0x50,0x0c,0x75,0x2c,
        0xb9,0x20,0xa8,0xdf,0x00,0xe8,0xa6,0x46,0x14,0x00,0x83,0xf8,0x07,0x74,0x1d,
        0x8b,0x46,0x10,0x8b,0x88,0x88,0x12,0x00,0x00,0x57,0xe8,0x42,0x30,0x04,0x00,
        0x8b,0x4e,0x10,0x8b,0x89,0x88,0x12,0x00,0x00,0xe8,0x04,0x3f,0x04,0x00};
    constexpr unsigned char busy[]{
        0x55,0x8b,0xec,0x56,0x8b,0xf1,0x8a,0x86,0x3c,0x26,0x00,0x00,0x84,0xc0,
        0x0f,0x85,0x15,0x02,0x00,0x00};
    constexpr unsigned char enableStore[]{0x8b,0x47,0x2c,0xc6,0x80,0x19,0x01,0x00,0x00};
    constexpr std::size_t enableOperand = 0x50334b;

    if (std::memcmp(image + 0x502830, render, sizeof(render)) != 0 ||
        std::memcmp(image + 0x816d30, renderSlot, sizeof(renderSlot)) != 0 ||
        std::memcmp(image + 0x50328c, grade, sizeof(grade)) != 0 ||
        std::memcmp(image + 0x5023d5, click, sizeof(click)) != 0 ||
        std::memcmp(image + 0x545460, busy, sizeof(busy)) != 0 ||
        std::memcmp(image + enableOperand - sizeof(enableStore), enableStore, sizeof(enableStore)) != 0 ||
        image[enableOperand] > 1) return false;

    image[enableOperand] = 1;
    return true;
}
