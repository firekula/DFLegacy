bool dfl::chapter_two::inventory_tab_detail::InstallImage(
    unsigned char* image, std::size_t bytes, PatchWriter write) noexcept
{
    if (!image || bytes != ImageSize || !write ||
        reinterpret_cast<std::uintptr_t>(image) > std::numeric_limits<std::uintptr_t>::max() - ImageSize)
        return false;
    if (std::memcmp(image + 0x6e2b0, AmountGate.data(), AmountGate.size()) != 0 ||
        std::memcmp(image + 0x70179, InsertGate.data(), InsertGate.size()) != 0 ||
        std::memcmp(image + 0x478b40, ManualButtons.data(), ManualButtons.size()) != 0)
        return false;

    auto patched = Selector;
    for (std::size_t i = 0; i < StoreSize; ++i) patched[StoreWithinSelector + i] = 0x90;
    if (std::memcmp(image + SelectorOffset, patched.data(), patched.size()) == 0) return true;
    if (std::memcmp(image + SelectorOffset, Selector.data(), Selector.size()) != 0) return false;

    const auto address = reinterpret_cast<std::uintptr_t>(image + SelectorOffset + StoreWithinSelector);
    if (!write(address, patched.data() + StoreWithinSelector, StoreSize))
    {
        // Protection restoration or instruction-cache flushing can fail after
        // the write. Restore the original bytes before reporting failure.
        write(address, Selector.data() + StoreWithinSelector, StoreSize);
        return false;
    }
    return true;
}

bool dfl::chapter_two::InstallInventoryTabPreservation(unsigned char* image, std::size_t bytes) noexcept
{
    return inventory_tab_detail::InstallImage(image, bytes, memory_patch::WriteBytes);
}
