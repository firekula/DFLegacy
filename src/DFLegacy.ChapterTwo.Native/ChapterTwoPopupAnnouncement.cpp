bool dfl::chapter_two::popup_announcement_detail::InstallImage(
    unsigned char* image,std::size_t bytes,PatchWriter write) noexcept
{
    if(!image||bytes!=ImageSize||!write||
        reinterpret_cast<std::uintptr_t>(image)>std::numeric_limits<std::uintptr_t>::max()-ImageSize)return false;
    if(std::memcmp(image+0x1dc5b,Dispatch,sizeof(Dispatch))||
        std::memcmp(image+0x2f75c,Target,sizeof(Target))||
        std::memcmp(image+0x2f770,Target,sizeof(Target))||
        std::memcmp(image+0x5ccfb0,Reader,sizeof(Reader)))return false;
    const auto* context=image+ContextOffset;
    constexpr auto after=PointerInContext+sizeof(Replacement);
    if(std::memcmp(context,PopupContext,PointerInContext)||
        std::memcmp(context+after,PopupContext+after,sizeof(PopupContext)-after))return false;
    auto* pointer=image+PointerOffset;
    if(std::memcmp(pointer,Replacement,sizeof(Replacement))==0)return true;
    if(std::memcmp(pointer,PopupContext+PointerInContext,sizeof(Replacement)))return false;
    const auto address=reinterpret_cast<std::uintptr_t>(pointer);
    if(write(address,Replacement,sizeof(Replacement)))return true;
    write(address,PopupContext+PointerInContext,sizeof(Replacement));
    return false;
}

bool dfl::chapter_two::InstallPopupAnnouncement(unsigned char* image,std::size_t bytes) noexcept
{
    return reinterpret_cast<std::uintptr_t>(image)==0x400000&&
        popup_announcement_detail::InstallImage(image,bytes,memory_patch::WriteBytes);
}
