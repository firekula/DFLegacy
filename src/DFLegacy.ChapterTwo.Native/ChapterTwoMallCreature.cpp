bool dfl::chapter_two::mall_creature_detail::InstallImage(unsigned char* image,std::size_t bytes,PatchWriter write) noexcept
{
    if(!image||bytes!=ImageSize||!write||reinterpret_cast<std::uintptr_t>(image)>std::numeric_limits<std::uintptr_t>::max()-ImageSize)return false;
    for(const auto& s:Context)if(std::memcmp(image+s.offset,s.data,s.size))return false;
    if(image[Visibility]==1)return true;
    if(image[Visibility]!=0)return false;
    constexpr unsigned char visible=1,hidden=0;
    const auto address=reinterpret_cast<std::uintptr_t>(image+Visibility);
    if(write(address,&visible,1))return true;
    // A protection/flush failure may be reported after the byte was written.
    write(address,&hidden,1);
    return false;
}

bool dfl::chapter_two::InstallMallCreature(unsigned char* image,std::size_t bytes) noexcept
{
    return image==reinterpret_cast<unsigned char*>(0x400000)&&mall_creature_detail::InstallImage(image,bytes,memory_patch::WriteBytes);
}
