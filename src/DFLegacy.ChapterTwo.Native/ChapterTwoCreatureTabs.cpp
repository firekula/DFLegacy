bool dfl::chapter_two::creature_tabs_detail::InstallImage(unsigned char* image,std::size_t bytes,PatchWriter write) noexcept
{
    if(!image||bytes!=ImageSize||!write||reinterpret_cast<std::uintptr_t>(image)>std::numeric_limits<std::uintptr_t>::max()-ImageSize)return false;
    for(const auto& s:Context)if(std::memcmp(image+s.offset,s.data,s.size))return false;
    constexpr std::size_t offsets[]={0x811534,0x811570};
    const unsigned char* tables[]={MainTable,AvatarTable};
    const std::uintptr_t callbacks[]={reinterpret_cast<std::uintptr_t>(&MainInput),reinterpret_cast<std::uintptr_t>(&AvatarInput)};
    std::array<bool,2> original{};
    for(std::size_t i=0;i<2;++i){
        if(std::memcmp(image+offsets[i],tables[i],8)||std::memcmp(image+offsets[i]+12,tables[i]+12,44))return false;
        original[i]=std::memcmp(image+offsets[i]+8,tables[i]+8,4)==0;
        if(!original[i]&&std::memcmp(image+offsets[i]+8,&callbacks[i],4))return false;
    }
    for(std::size_t i=0;i<2;++i){if(!original[i])continue;
        if(write(reinterpret_cast<std::uintptr_t>(image+offsets[i]+8),&callbacks[i],4))continue;
        for(std::size_t n=i+1;n>0;--n){const auto j=n-1;if(original[j])write(reinterpret_cast<std::uintptr_t>(image+offsets[j]+8),tables[j]+8,4);}
        return false;
    }
    return true;
}

bool dfl::chapter_two::InstallCreatureTabs(unsigned char* image,std::size_t bytes) noexcept
{
    return image==reinterpret_cast<unsigned char*>(0x400000)&&creature_tabs_detail::InstallImage(image,bytes,memory_patch::WriteBytes);
}
