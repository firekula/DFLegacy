int dfl::chapter_two::external_string_table_detail::ExtractForExecutable(
    const wchar_t* executable,const char* destination,ResolveClientPath resolve,BuiltinExtractor builtin) noexcept
{
    wchar_t source[MAX_PATH]{};
    if(!AbsoluteExecutable(executable)||!destination||!*destination||!resolve||
        !external_string_table::BuildPluginPath(executable,source,MAX_PATH))return -1;
    // Reuse C1's encoding, size and missing-file policy, never its C1 hook or addresses.
    // The resolver returns the container staging path already selected by the host.
    return external_string_table::ExtractOrFallback(source,resolve(destination),destination,builtin);
}

bool dfl::chapter_two::external_string_table_detail::InstallImage(
    unsigned char* image,std::size_t bytes,std::uintptr_t hook,PatchWriter write) noexcept
{
    if(!image||bytes!=ImageSize||!hook||!write||
        reinterpret_cast<std::uintptr_t>(image)>std::numeric_limits<std::uintptr_t>::max()-ImageSize)return false;
    if(std::memcmp(image+0x5bfbb0,Extractor,sizeof(Extractor))||
        std::memcmp(image+0x5bfc40,Decode,sizeof(Decode))||
        std::memcmp(image+0x5bfcd0,Parser,sizeof(Parser))||
        std::memcmp(image+0x16b0,Resolve,sizeof(Resolve))||
        std::memcmp(image+0x81d108,"File",5))return false;
    auto* context=image+ContextOffset;
    if(std::memcmp(context,Context,CallInContext)||
        std::memcmp(context+CallInContext+CallSize,Context+CallInContext+CallSize,sizeof(Context)-CallInContext-CallSize))return false;
    auto* call=context+CallInContext;
    std::array<unsigned char,CallSize> replacement{0xe8,0,0,0,0};
    const auto address=reinterpret_cast<std::uintptr_t>(call);
    const auto displacement=static_cast<std::uint32_t>(hook-address-CallSize);
    std::memcpy(replacement.data()+1,&displacement,sizeof(displacement));
    if(std::memcmp(call,replacement.data(),CallSize)==0)return true;
    if(std::memcmp(call,Context+CallInContext,CallSize))return false;
    if(write(address,replacement.data(),CallSize))return true;
    write(address,Context+CallInContext,CallSize);
    return false;
}

bool dfl::chapter_two::InstallExternalStringTable(unsigned char* image,std::size_t bytes) noexcept
{
    return reinterpret_cast<std::uintptr_t>(image)==0x400000&&
        external_string_table_detail::InstallImage(image,bytes,reinterpret_cast<std::uintptr_t>(&ExtractExternal),memory_patch::WriteBytes);
}
