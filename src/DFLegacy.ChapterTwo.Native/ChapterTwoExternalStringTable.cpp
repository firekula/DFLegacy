    bool AbsoluteExecutable(const wchar_t* path) noexcept
    {
        if(!path)return false;
        const auto size=std::wcslen(path);
        return size>3&&(((path[0]>=L'A'&&path[0]<=L'Z')||(path[0]>=L'a'&&path[0]<=L'z'))&&
            path[1]==L':'&&(path[2]==L'\\'||path[2]==L'/')||
            (path[0]==L'\\'&&path[1]==L'\\'));
    }

    int __cdecl ExtractExternal(const char* destination) noexcept
    {
        wchar_t executable[MAX_PATH]{};
        const DWORD length=GetModuleFileNameW(nullptr,executable,MAX_PATH);
        if(length==0||length>=MAX_PATH)return -1;
        return dfl::chapter_two::external_string_table_detail::ExtractForExecutable(executable,destination,
            reinterpret_cast<dfl::chapter_two::external_string_table_detail::ResolveClientPath>(0x4016b0),
            reinterpret_cast<dfl::chapter_two::external_string_table_detail::BuiltinExtractor>(0x9bfbb0));
    }
